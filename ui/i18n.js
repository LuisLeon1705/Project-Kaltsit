const I18N = { es: I18N_ES, en: I18N_EN };
const I18N_LOCALES = { es: "es", en: "en" };
let i18nLang = "es";
const i18nWarned = new Set();
const i18nListeners = [];

function t(key, vars) {
  let s = I18N[i18nLang][key];
  if (s === undefined) {
    s = I18N.es[key];
    if (!i18nWarned.has(key)) {
      i18nWarned.add(key);
      console.warn(`i18n: missing key "${key}" for "${i18nLang}"`);
    }
  }
  if (s === undefined) s = key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : String(vars[name])));
  return s;
}

// A key that may not exist (a value that came from the backend): the text, or `fallback`.
function tOr(key, fallback) {
  return I18N[i18nLang][key] !== undefined ? I18N[i18nLang][key] : I18N.es[key] !== undefined ? t(key) : fallback;
}

function getLang() {
  return i18nLang;
}

// The locale for dates and times.
function locale() {
  return I18N_LOCALES[i18nLang];
}

function setLang(code) {
  const next = I18N[code] ? code : "es";
  const changed = next !== i18nLang;
  i18nLang = next;
  if (typeof document !== "undefined") {
    document.documentElement.lang = next;
    // Two tags that CSS prints after a message's author.
    document.documentElement.style.setProperty("--tag-alone", JSON.stringify(t("msg.alone")));
    document.documentElement.style.setProperty("--tag-ghost", JSON.stringify(t("msg.ghost")));
  }
  if (changed) for (const fn of i18nListeners) fn(next);
}

// Registers what to redraw when the language changes.
function onLang(fn) {
  i18nListeners.push(fn);
}

function applyI18n(root) {
  const scope = root || document;
  for (const el of scope.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of scope.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of scope.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of scope.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
}

if (typeof module !== "undefined" && module.exports) module.exports = { I18N, t, tOr, setLang, getLang, locale, applyI18n, onLang };
